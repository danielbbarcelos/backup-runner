LOCALES: dict[str, dict[str, str]] = {"pt-BR": PT, "en-US": EN}

_locale = "pt-BR"


def set_locale(nome: str) -> None:
    global _locale
    if nome in LOCALES:
        _locale = nome


def current_locale() -> str:
    return _locale


def _detect() -> str:
    escolhido = os.environ.get("BACKUP_RUNNER_LOCALE")
    if escolhido in LOCALES:
        return escolhido
    lang = os.environ.get("LANG", "")
    if lang.startswith("en"):
        return "en-US"
    return "pt-BR"


_locale = _detect()


def t(chave: str, **kwargs: object) -> str:
    texto = LOCALES.get(_locale, PT).get(chave) or PT.get(chave) or chave
    if kwargs:
        try:
            return texto.format(**kwargs)
        except (KeyError, IndexError):
            return texto
    return texto
